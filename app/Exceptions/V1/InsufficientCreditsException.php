<?php

namespace App\Exceptions\V1;

/**
 * ДОМЕННОЕ исключение: у отправителя недостаточно кредитов для подарка.
 *
 * Пакет 5 (рекомендация №3 аудита Шага 1 — единый конвейер ошибок).
 *
 * ЗАЧЕМ: раньше SendGiftAction бросал голое \Exception с «человекочитаемым»
 * текстом, а GiftController ловил ЛЮБОЙ \Exception и отдавал его getMessage()
 * наружу с 402. Это значило: любая внутренняя ошибка (БД недоступна, упал
 * Redis, баг в сериализации) тоже улетала клиенту с текстом внутреннего
 * исключения и кодом 402 «не хватает денег» — и утечка внутренностей, и
 * неверный статус.
 *
 * ТЕПЕРЬ: контроллер ловит ТОЛЬКО это доменное исключение → честный 402 с
 * пользовательским текстом. Всё прочее падает в общий конвейер → 500 без
 * внутренних деталей (детали — в лог).
 */
class InsufficientCreditsException extends \RuntimeException
{
    public function __construct(
        string $message = 'Недостаточно кредитов для совершения покупки.',
    ) {
        parent::__construct($message);
    }
}
